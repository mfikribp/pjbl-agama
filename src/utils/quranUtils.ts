export function getVerseInfo(globalId: number) {
  let count = 0;
  for (let i = 0; i < SURA_DATA.length; i++) {
    const sura = SURA_DATA[i];
    if (globalId <= count + sura.verses) {
      return {
        surahName: sura.name,
        surahIndex: i + 1,
        verseNumber: globalId - count
      };
    }
    count += sura.verses;
  }
  return null;
}

export function formatVerseReference(globalId: number) {
  const info = getVerseInfo(globalId);
  if (!info) return `Ayat Ke-${globalId}`;
  return `${info.surahName} Ayat ${info.verseNumber}`;
}

export function replaceVerseRefs(html: string) {
  return html.replace(/\[Ayat Ke-(\d+)\]/g, (match, p1) => {
    const globalId = parseInt(p1);
    return `[${formatVerseReference(globalId)}]`;
  });
}
